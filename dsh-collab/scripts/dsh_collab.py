def build_dsh_argv(
    dsh_cmd: str,
    session_id: str | None,
    argv_prefix: Sequence[str] | None = None,
) -> list[str] | str:
    """`dsh headless --json [-session-id <known>] -`; task text arrives on stdin.

    The trailing `-` is the documented "read the task from stdin" argument (see
    `dsh headless --help`).  An unknown session id is never passed: DSH treats an
    unknown id as a hard error, and guessing would silently attach the task to
    the wrong conversation.

    `argv_prefix` (tests only) supplies a launcher that executes DSH's arguments
    itself, e.g. `[python.exe, fixture.py]`; `dsh_cmd` is then unused and must not
    be routed through the shell.

    Returns a list, or a raw command-line string when cmd.exe is required.
    """
    args = ["headless", "--json"]
    if session_id is not None:
        args += ["--session-id", validate_session_id(session_id)]
    args.append("-")
    if argv_prefix:
        return [*argv_prefix, *args]
    return plan_launch(dsh_cmd, args)[0]


def terminate_process_tree(pid: int, timeout: float = 15.0) -> dict[str, Any]:
    """Kill a Windows process tree via taskkill on the PID we own.

    `taskkill /T` is used so grandchildren (a `.cmd` shim hands off to node, which
    may spawn more children) cannot survive as orphans.  `pid` is only ever the
    direct child the run itself spawned.
    """
    info: dict[str, Any] = {"pid": pid, "method": None, "ok": False, "detail": ""}
    if pid <= 0:
        info["detail"] = "invalid pid"
        return info
    if os.name == "nt":
        try:
            proc = subprocess.run(
                ["taskkill", "/F", "/T", "/PID", str(pid)],
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                timeout=timeout,
                check=False,
            )
            info["method"] = "taskkill"
            info["ok"] = proc.returncode == 0
            info["detail"] = _decode(proc.stdout or b"").strip()[:400]
        except (OSError, subprocess.SubprocessError) as exc:
            info["method"] = "taskkill"
            info["detail"] = f"taskkill failed: {exc}"
    else:
        try:
            os.killpg(os.getpgid(pid), signal.SIGKILL)
            info.update(method="killpg", ok=True)
        except OSError as exc:
            info.update(method="killpg", ok=False, detail=str(exc))
    return info


def _is_alive(pid: int) -> bool:
    if pid <= 0:
        return False
    if os.name == "nt":
        kernel32 = ctypes.windll.kernel32
        handle = kernel32.OpenProcess(0x1000, False, pid)  # PROCESS_QUERY_LIMITED
        if not handle:
            return False
        try:
            code = ctypes.c_ulong(0)
            if kernel32.GetExitCodeProcess(handle, ctypes.byref(code)):
                return code.value == 259  # STILL_ACTIVE
            return True
        finally:
            kernel32.CloseHandle(handle)
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        return False


class TurnResult:
    """Outcome of one DSH turn (headless subprocess or Desktop session)."""

    def __init__(self) -> None:
        self.session_id: str | None = None
        self.expected_session_id: str | None = None
        self.session_mismatch: str | None = None
        self.final_text: str = ""
        self.final_seen: bool = False
        self.text_parts: list[str] = []
        self.turns: int = 0
        self.returncode: int | None = None
        self.timed_out: bool = False
        self.interrupted: bool = False
        self.error: str | None = None
        self.bad_lines: int = 0
        self.event_count: int = 0
        self.event_types: dict[str, int] = {}
        self.kill_info: dict[str, Any] | None = None
        self.stderr_tail: str = ""
        self.stdin_error: str | None = None
        self.reader_error: str | None = None
        self.readers_hung: bool = False
        self.classification: dict[str, Any] | None = None
        # Desktop-only facts.
        self.workspace_id: str | None = None
        self.actual_model: dict[str, Any] | None = None
        self.cancel_info: dict[str, Any] | None = None
        self.request_id: str | None = None
        self.turn_reason: dict[str, Any] | None = None

    @property
    def reply(self) -> str:
        return (self.final_text or "\n".join(p for p in self.text_parts if p)).strip()

    @property
    def ok(self) -> bool:
        return (not self.timed_out and not self.interrupted and self.error is None
                and self.returncode == 0 and bool(self.session_id)
                and self.final_seen and bool(self.reply))


# Event types whose payload is model-private reasoning.  They are counted and
# recorded by type only; their text is never stored or printed.
REASONING_EVENT_TYPES = frozenset({"thinking", "reasoning", "reasoning_delta"})


def redact_event(event: dict[str, Any]) -> dict[str, Any]:
    """Strip private reasoning text, keeping only the event's shape.

    `events.jsonl` is a user-readable log, so hidden chain-of-thought must never
    land in it.  Type and timing are preserved; the content is elided.
    """
    etype = str(event.get("type", ""))
    if etype in REASONING_EVENT_TYPES:
        redacted = {k: v for k, v in event.items()
                    if k in ("type", "id", "phase", "turn", "timestamp", "ts")}
        redacted["_redacted"] = "reasoning omitted"
        return redacted
    return event


def apply_protocol_event(result: TurnResult, event: dict[str, Any],
                         diag: Callable[[str], None]) -> None:
    """Apply one NDJSON event to a turn result.

    Shared by the headless CLI and the Desktop transport, because both surface
    the same `session` / `text` / `final` / `status` vocabulary to the rest of
    the bridge.  A `session` event is validated before the id is ever used.
    """
    etype = str(event.get("type", "unknown"))
    if etype == "session":
        sid = event.get("sessionId") or event.get("session_id")
        if not isinstance(sid, str) or not sid:
            result.error = result.error or "session event carried no usable id"
            return
        try:
            validate_session_id(sid)
        except UsageError:
            result.error = (
                "dsh reported an unsafe session id; refusing to use it: "
                f"{sid[:64]!r}"
            )
            return
        if result.expected_session_id and sid != result.expected_session_id:
            # Silently continuing would run the task in a different context
            # than the one the caller believes they are resuming.
            result.session_mismatch = (
                f"expected session {result.expected_session_id!r} but dsh "
                f"reported {sid!r}"
            )
            result.error = result.error or (
                "dsh resumed a different session than requested: "
                + result.session_mismatch
            )
            return
        if result.session_id is None:
            result.session_id = sid
    elif etype == "text":
        text = event.get("text")
        if isinstance(text, str):
            result.text_parts.append(text)
    elif etype == "final":
        text = event.get("text")
        if isinstance(text, str):
            result.final_text = text
            result.final_seen = True
    elif etype == "status" and event.get("phase") == "turn_start":
        turn = event.get("turn")
        if isinstance(turn, int):
            result.turns = turn


class DshRunner:
    """Spawns DSH once per turn, streaming NDJSON events to a sink.

    `spawn` is injectable, and `argv_prefix` lets a test execute a fixture
    instead of the real CLI while DSH's own argv is still produced by
    `build_dsh_argv` and remains fully validated.
    """

    def __init__(self, dsh_cmd: str, cwd: str, timeout: float,
                 on_event: Callable[[dict[str, Any]], None] | None = None,
                 on_session: Callable[[str], None] | None = None,
                 on_diag: Callable[[str], None] | None = None,
                 spawn: Callable[..., subprocess.Popen] | None = None,
                 argv_prefix: Sequence[str] | None = None):
        self.dsh_cmd = dsh_cmd
        self.cwd = cwd
        self.timeout = float(timeout)
        self.on_event = on_event
        self.on_session = on_session
        self.on_diag = on_diag
        self._spawn = spawn or subprocess.Popen
        self.argv_prefix = list(argv_prefix or [])

    # -- internals ---------------------------------------------------------

    def _diag(self, message: str) -> None:
        if self.on_diag is not None:
            self.on_diag(message)

    def _emit(self, event: dict[str, Any]) -> None:
        if self.on_event is not None:
            self.on_event(event)

    def _handle_line(self, raw: str, result: TurnResult) -> None:
        raw = raw.strip()
        if not raw:
            return
        try:
            event = json.loads(raw)
        except json.JSONDecodeError as exc:
            result.bad_lines += 1
            self._diag(f"unparseable NDJSON line ({exc.msg}): {raw[:300]}")
            self._emit({"_invalid": True, "_error": exc.msg})
            return
        if not isinstance(event, dict):
            result.bad_lines += 1
            self._diag(f"non-object NDJSON event: {raw[:300]}")
            self._emit({"_invalid": True,
                        "_error": "event is not a JSON object"})
            return

        result.event_count += 1
        etype = str(event.get("type", "unknown"))
        result.event_types[etype] = result.event_types.get(etype, 0) + 1
        self._emit(event)

        before_session = result.session_id
        apply_protocol_event(result, event, self._diag)
        if result.session_id is not None and before_session is None:
            # Persist immediately: a later crash must not lose the session.
            if self.on_session is not None:
                self.on_session(result.session_id)

    def _drain(self, stream: Any, result: TurnResult, is_stderr: bool) -> None:
        try:
            for raw_line in iter(stream.readline, b""):
                text = _decode(raw_line)
                if is_stderr:
                    result.stderr_tail = (result.stderr_tail + text)[-4000:]
                    self._diag(f"stderr: {text.rstrip()}")
                else:
                    self._handle_line(text, result)
        except (OSError, ValueError) as exc:
            if result.reader_error is None:
                result.reader_error = f"failed reading dsh output: {exc}"
        except Exception as exc:  # unexpected: never swallow silently
            if result.reader_error is None:
                result.reader_error = f"{type(exc).__name__}: {exc}"
        finally:
            with contextlib.suppress(Exception):
                stream.close()

    def _write_stdin(self, stream: Any, data: bytes, result: TurnResult,
                     done: threading.Event) -> None:
        try:
            stream.write(data)
            stream.flush()
        except (OSError, ValueError) as exc:
            result.stdin_error = f"could not deliver the task text over stdin: {exc}"
        finally:
            with contextlib.suppress(Exception):
                stream.close()
            done.set()

    # -- public ------------------------------------------------------------

    def run(self, session_id: str | None, task_text: str) -> TurnResult:
        result = TurnResult()
        result.session_id = None
        result.expected_session_id = session_id
        argv = build_dsh_argv(self.dsh_cmd, session_id, self.argv_prefix)
        stdin_data = task_text.encode("utf-8")

        popen_kwargs: dict[str, Any] = {
            "cwd": self.cwd,
            "stdin": subprocess.PIPE,
            "stdout": subprocess.PIPE,
            "stderr": subprocess.PIPE,
        }
        if not self.argv_prefix:
            _, launch_kwargs = plan_launch(self.dsh_cmd, [])
            popen_kwargs.update(launch_kwargs)
        if os.name == "nt":
            # Own process group => taskkill /T can reach the whole tree.
            popen_kwargs["creationflags"] = getattr(
                subprocess, "CREATE_NEW_PROCESS_GROUP", 0)
        else:
            # Own session => os.killpg can reach the whole tree.
            popen_kwargs["start_new_session"] = True

        proc = self._spawn(argv, **popen_kwargs)
        readers: list[threading.Thread] = []
        deadline = time.monotonic() + self.timeout
        try:
            if proc.stdout is None or proc.stderr is None:
                raise TaskError("dsh subprocess pipes were not created")
            for stream, is_err in ((proc.stdout, False), (proc.stderr, True)):
                thread = threading.Thread(
                    target=self._drain, args=(stream, result, is_err), daemon=True
                )
                thread.start()
                readers.append(thread)

            # The task text is written from its own thread: a child that never
            # reads a large prompt must not be able to block the main thread past
            # the timeout.
            stdin_done = threading.Event()
            if proc.stdin is not None:
                writer = threading.Thread(
                    target=self._write_stdin,
                    args=(proc.stdin, stdin_data, result, stdin_done),
                    daemon=True,
                )
                writer.start()

            try:
                result.returncode = proc.wait(
                    timeout=max(0.0, deadline - time.monotonic()))
            except subprocess.TimeoutExpired:
                result.timed_out = True
                result.error = f"timeout after {self.timeout:g}s"
                self._terminate(proc, result, "timeout")
            except KeyboardInterrupt:
                result.interrupted = True
                result.error = "interrupted by user"
                self._terminate(proc, result, "interrupt")
            finally:
                # Bounded: the writer thread is a daemon and its stream belongs
                # to a process that is already gone.
                if not stdin_done.wait(timeout=5.0):
                    result.stdin_error = "task input writer did not finish"
        except BaseException:
            # Any unexpected failure must still not leak the child.
            with contextlib.suppress(Exception):
                if proc.poll() is None:
                    self._terminate(proc, result, "exception")
            raise
        finally:
            for thread in readers:
                thread.join(timeout=10.0)
            for thread in readers:
                if thread.is_alive():
                    # A reader still blocked after the process is gone means the
                    # output stream was not consumed cleanly.
                    result.readers_hung = True
            if proc.poll() is None:  # defensive: never leave an orphan
                with contextlib.suppress(Exception):
                    self._terminate(proc, result, "cleanup")

        self._finalize(result)
        return result

    def _finalize(self, result: TurnResult) -> None:
        """Decide the turn outcome from exit code plus protocol evidence."""
        if result.timed_out or result.interrupted:
            return
        if result.stdin_error and result.error is None:
            result.error = result.stdin_error
            return
        if result.reader_error and result.error is None:
            result.error = result.reader_error
            return
        if result.returncode is None:
            result.error = "dsh process did not report an exit code"
            return
        if result.returncode != 0:
            tail = result.stderr_tail.strip()[-400:]
            result.error = f"dsh exited with code {result.returncode}"
            if tail:
                result.error += f": {tail}"
            return
        if not result.session_id:
            result.error = result.error or (
                "dsh produced no usable session id; session not established")
            return
        if not result.final_seen:
            # A stream that ends without `final` was truncated or interrupted;
            # whatever text arrived is not a completed turn.
            result.error = (
                "dsh output ended without a final event; the turn did not "
                "complete (stderr tail: "
                f"{result.stderr_tail.strip()[-200:] or 'empty'})"
            )
            return
        if not result.reply:
            result.error = "dsh final event contained no usable reply"
            return
        if result.readers_hung:
            result.error = (
                "dsh output readers did not finish after the process exited; "
                "refusing to treat the turn as complete"
            )

    def _terminate(self, proc: subprocess.Popen, result: TurnResult,
                   reason: str) -> None:
        pid = proc.pid
        info = terminate_process_tree(pid)
        if not info.get("ok"):
            # taskkill refused; still try the direct handle so we do not
            # knowingly leave an orphan behind.
            with contextlib.suppress(Exception):
                proc.kill()
            info["fallback"] = "Popen.kill"
            if not info.get("detail"):
                info["detail"] = "taskkill reported failure"
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            info["detail"] += "; owned process did not exit after termination"
        info["alive_after"] = proc.poll() is None
        result.kill_info = info
        self._diag(f"terminated pid {pid} ({reason}): {info}")


