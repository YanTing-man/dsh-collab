def utc_now() -> str:
    """UTC timestamp, ISO-8601 with a trailing Z, second precision."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def configure_stdio() -> None:
    """Force UTF-8 on our own streams.

    Without this a Chinese Windows console (GBK) can turn a report containing
    non-ASCII paths or replies into a UnicodeEncodeError.
    """
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            with contextlib.suppress(Exception):
                reconfigure(encoding="utf-8", errors="replace")


def new_task_id() -> str:
    return uuid.uuid4().hex[:12]


def normalize_workspace(path: str | os.PathLike[str]) -> str:
    """Canonical, case-normalised, fully-resolved workspace path.

    Case normalisation matters on Windows: `E:\\Proj` and `e:\\proj` are the same
    directory and must not be able to masquerade as two different projects.
    """
    p = Path(path).expanduser()
    if not p.is_absolute():
        raise UsageError(f"workspace must be an absolute path: {path!r}")
    resolved = p.resolve(strict=False)
    return os.path.normcase(str(resolved))


def require_workspace(path: str | os.PathLike[str]) -> str:
    """Normalise a workspace and require that it exists and is a directory."""
    norm = normalize_workspace(path)
    if not os.path.isdir(norm):
        raise UsageError(f"workspace does not exist or is not a directory: {path}")
    return norm


def validate_task_id(task_id: str) -> str:
    """Reject anything that could escape the task root (traversal-proof)."""
    if not isinstance(task_id, str) or not TASK_ID_RE.match(task_id):
        raise UsageError(
            "invalid task id (expected 4-32 lowercase alphanumerics): "
            f"{task_id!r}"
        )
    return task_id


def validate_session_id(session_id: str) -> str:
    """Validate before the value is ever passed to a .cmd shim.

    The charset is deliberately tiny: no whitespace, no quotes, and a first
    character that can never be read as an option, so a session id cannot become
    an argument-injection vector on any platform.
    """
    if not isinstance(session_id, str) or not session_id:
        raise UsageError(f"refusing to use empty or non-string session id: "
                         f"{session_id!r}")
    if not SESSION_ID_RE.match(session_id):
        raise UsageError(f"refusing to use suspicious session id: {session_id!r}")
    return session_id


def _decode(data: bytes) -> str:
    return data.decode("utf-8", "replace")


def validate_dsh_cmd(cmd: str) -> str:
    """Reject a `--dsh-cmd`/`$DSH_CMD` override that is not a plain path.

    Only an executable path is accepted, never extra arguments or shell text, so
    no user-supplied string can extend the command that is launched.
    """
    if not cmd or cmd.strip() != cmd:
        raise UsageError(f"--dsh-cmd/DSH_CMD must be a plain path: {cmd!r}")
    if any(ch in cmd for ch in "\r\n\t"):
        raise UsageError(f"--dsh-cmd/DSH_CMD must not contain newlines: {cmd!r}")
    if cmd.startswith("-"):
        raise UsageError(f"--dsh-cmd/DSH_CMD must be a path, not an option: {cmd!r}")
    if os.name == "nt":
        if not os.path.isabs(cmd):
            raise UsageError(f"--dsh-cmd/DSH_CMD must be an absolute path: {cmd!r}")
        if not cmd.lower().endswith((".cmd", ".bat", ".exe")):
            raise UsageError(
                "--dsh-cmd/DSH_CMD must name a .cmd, .bat or .exe: "
                f"{cmd!r}"
            )
    return cmd


def plan_launch(dsh_cmd: str, args: Sequence[str]) -> tuple[list[str] | str, dict[str, Any]]:
    """Decide how to launch the DSH executable.

    Returns `(argv_or_command_line, extra_popen_kwargs)`.

    A `.cmd`/`.bat` shim is not a real executable, so it must be run through
    `cmd.exe`.  Passing cmd a *list* lets `subprocess` re-quote each argument,
    which mangles a shim path containing spaces; the reliable form is a single
    raw command *string* of the shape

        cmd.exe /d /s /c ""C:\\path with spaces\\dsh.cmd" headless --json -"

    where the command token gets doubled outer quotes.  Everything variable
    (the task text) still travels over stdin, so no caller text ever becomes part
    of this command line.
    """
    if os.name == "nt" and dsh_cmd.lower().endswith((".cmd", ".bat")):
        comspec = os.environ.get("COMSPEC") or "cmd.exe"
        command = '"' + dsh_cmd + '"'
        command_line = f'"{comspec}" /d /s /c "{command} {" ".join(args)}"'
        return command_line, {"executable": comspec}
    return [dsh_cmd, *args], {}


def importable_argv(cmd: str, args: Sequence[str]) -> list[str] | str:
    """Backwards-compatible wrapper around `plan_launch`."""
    return plan_launch(cmd, args)[0]


