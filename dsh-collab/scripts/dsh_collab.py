class Context:
    """Everything a command needs, so tests can inject a fake runner."""

    def __init__(self, store: TaskStore, dsh_cmd: str,
                 runner_factory: Callable[..., DshRunner] | None = None,
                 spawn: Callable[..., subprocess.Popen] | None = None,
                 argv_prefix: Sequence[str] | None = None,
                 dsh_cmd_source: str = "default",
                 stdout: Any = None,
                 desktop_endpoint: Path | None = None,
                 electron_exe: str = DEFAULT_ELECTRON_EXE,
                 desktop_runner_factory: Callable[..., DesktopRunner] | None = None,
                 default_backend: str = DEFAULT_BACKEND):
        self.store = store
        self.dsh_cmd = dsh_cmd
        # Where dsh_cmd came from: "argument", "env" or "default".
        self.dsh_cmd_source = dsh_cmd_source
        self._runner_factory = runner_factory or DshRunner
        self._spawn = spawn
        self._argv_prefix = list(argv_prefix or [])
        self.stdout = stdout or sys.stdout
        self.desktop_endpoint = Path(desktop_endpoint) if desktop_endpoint else None
        self.electron_exe = electron_exe
        self.desktop_helper = desktop_helper_path()
        self._desktop_runner_factory = desktop_runner_factory or DesktopRunner
        self.default_backend = normalize_backend(default_backend)

    def runner(self, cwd: Path | str, timeout: float,
               on_event: Callable[[dict[str, Any]], None] | None = None,
               on_session: Callable[[str], None] | None = None,
               on_diag: Callable[[str], None] | None = None) -> DshRunner:
        """Build a runner whose working directory is the task's workspace.

        Execution must happen inside the authorised project, never inside the
        log/state directory.
        """
        kwargs: dict[str, Any] = {}
        if self._spawn is not None:
            kwargs["spawn"] = self._spawn
        if self._argv_prefix:
            kwargs["argv_prefix"] = self._argv_prefix
        return self._runner_factory(
            self.dsh_cmd, str(cwd), timeout,
            on_event=on_event, on_session=on_session, on_diag=on_diag, **kwargs
        )

    def desktop_runner(self, cwd: Path | str, timeout: float,
                       on_event: Callable[[dict[str, Any]], None] | None = None,
                       on_session: Callable[[str], None] | None = None,
                       on_diag: Callable[[str], None] | None = None,
                       *, session_id: str | None = None,
                       create: dict[str, Any] | None = None) -> DesktopRunner:
        """Build the Desktop transport for one turn inside the workspace."""
        if self.desktop_endpoint is None:
            raise TaskError("no Desktop endpoint is configured")
        kwargs: dict[str, Any] = {}
        if self._spawn is not None:
            kwargs["spawn"] = self._spawn
        return self._desktop_runner_factory(
            self.electron_exe, self.desktop_helper, self.desktop_endpoint,
            str(cwd), timeout,
            on_event=on_event, on_session=on_session, on_diag=on_diag,
            session_id=session_id, create=create, **kwargs
        )

    def desktop_invoke(self, command: str, payload: dict[str, Any] | None, *,
                       cwd: str | None = None, timeout: float = 120.0) -> DesktopHelperCall:
        """Run one one-shot Desktop helper command (models/prepare/select-model)."""
        if self.desktop_endpoint is None:
            raise TaskError("no Desktop endpoint is configured")
        kwargs: dict[str, Any] = {}
        if self._spawn is not None:
            kwargs["spawn"] = self._spawn
        return invoke_desktop_helper(
            self.electron_exe, self.desktop_helper, self.desktop_endpoint,
            command, payload, cwd=cwd or os.getcwd(), timeout=timeout, **kwargs
        )


def read_message_file(path: str) -> str:
    """Read a UTF-8 message file.  The file itself may be temporary: the text is
    copied into the task logs, so nothing later depends on the staging file."""
    p = Path(path).expanduser()
    if not p.is_file():
        raise UsageError(f"message file not found: {path}")
    try:
        # utf-8-sig transparently accepts a BOM (which Notepad and PowerShell
        # redirection add) while still reading plain UTF-8 correctly.
        text = p.read_text(encoding="utf-8-sig")
    except UnicodeDecodeError as exc:
        raise UsageError(f"message file is not valid UTF-8: {path} ({exc})") from exc
    except OSError as exc:
        raise UsageError(f"could not read message file {path}: {exc}") from exc
    if not text.strip():
        raise UsageError(f"message file is empty: {path}")
    return text


def emit(payload: dict[str, Any], stdout: Any = None) -> None:
    stream = stdout or sys.stdout
    stream.write(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")
    with contextlib.suppress(Exception):
        stream.flush()


def summary(task: dict[str, Any], store: TaskStore, *, reply: str = "",
            error: str | None = None, ok: bool = True,
            command: str | None = None,
            extra: dict[str, Any] | None = None) -> dict[str, Any]:
    task_id = str(task.get("id"))
    payload = {
        "ok": ok,
        "command": command if command is not None else "unknown",
        "task_id": task_id,
        "backend": task_backend(task),
        "session_id": task.get("session_id"),
        "workspace_id": task.get("workspace_id"),
        "selected_model": task.get("selected_model"),
        "actual_model": task.get("actual_model"),
        "status": task.get("status"),
        "classification": task.get("classification"),
        "reply": reply,
        "error": error if error is not None else task.get("last_error"),
        "logs": store.logs(task_id),
    }
    if extra:
        payload.update(extra)
    return payload


