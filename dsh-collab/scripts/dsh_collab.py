#!/usr/bin/env python3
"""dsh_collab - GPT(planner/reviewer) <-> DSH(executor) collaboration bridge.

Python 3.12 stdlib CLI with adjacent dsh_evidence.py for review/observe.
No third-party imports and no dependence on any particular project.

Responsibilities
----------------
* `start`  : create a task and NEW DSH session (Desktop by default), send turn 1.
* `send`   : continue an existing task in its preserved DSH session.
* `review` : record GPT evidence / verdict ONLY.  Never calls DSH.
* `show`   : print one task record.
* `list`   : list tasks (optionally scoped to a workspace).
* `doctor` : report DSH / Python availability.  No inference, no credentials.

Safety properties
-----------------
* The task text NEVER appears in argv or in a shell command string: it is written
  to the child's stdin as UTF-8.  The shell is never involved (no shell=True),
  so shell metacharacters in the message are inert.
* Session ids are strictly validated before being handed to a .cmd shim, so a
  hostile/odd session id cannot become an argument-injection vector.
* Per-task OS file locks (msvcrt on Windows, flock on POSIX) serialise
  send/review; the lock dies with the process, so a crash cannot leave a lock
  behind.
* Nonzero exit, timeout, interruption, unparseable output, missing session or a
  missing usable reply are all recorded as failures.  Nothing is auto-retried.
"""

