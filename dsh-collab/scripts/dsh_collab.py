def _marker_value(text: str, marker: str) -> str | None:
    """Find `MARKER: value` at the start of a line (case-insensitive)."""
    pattern = re.compile(rf"^[ \t]*{marker}[ \t]*:[ \t]*(.+)$",
                         re.MULTILINE | re.IGNORECASE)
    matches = pattern.findall(text or "")
    if not matches:
        return None
    return matches[-1].strip() or None


def classify_reply(final_text: str) -> dict[str, Any]:
    """Classify a DSH reply from the FINAL text by explicit line markers only.

    Incidental words such as "question" inside prose must not be able to turn a
    normal completion into a blocking question, so only anchored `MARKER:` lines
    count.  A QUESTION means DSH is blocked and needs a decision from its peer
    (GPT), which outranks any completion marker in the same reply.
    """
    final_text = final_text or ""
    question = _marker_value(final_text, "QUESTION")
    review_ready = _marker_value(final_text, "REVIEW_READY")
    dsh_result = _marker_value(final_text, "DSH_RESULT")
    return {
        "question": question,
        "review_ready": review_ready,
        "dsh_result": dsh_result,
        "finished": bool(not question and (dsh_result or review_ready)),
    }


def status_for_classification(classification: dict[str, Any] | None) -> str:
    """Map a successful turn's classification onto the task status.

    A blocked QUESTION needs a decision; REVIEW_READY / DSH_RESULT wait for the
    reviewer.  DSH reporting completion is never an approval.
    """
    classification = classification or {}
    if classification.get("question"):
        return STATUS_NEEDS_DECISION
    return STATUS_AWAITING_REVIEW


