def _prepare_run(task: dict[str, Any], workspace: str, message: str, *,
                 first: bool) -> str:
    """Build the exact text that will be piped to DSH.  Not logged verbatim.

    The turn-1 brief is injected only for a brand-new session; later turns send
    the user's text unchanged into the preserved session.
    """
    if first:
        return FIRST_TURN_BRIEF.format(workspace=workspace) + "\n--- task ---\n" + message
    return message


def _is_first_turn(task: dict[str, Any]) -> bool:
    """True when the task has not completed a turn yet.

    A task `prepare`d for Desktop has a session but zero rounds, so its first
    `send` still carries the turn-1 brief.
    """
    return int(task.get("rounds") or 0) == 0


def run_turn(ctx: Context, task: dict[str, Any], message: str, *, timeout: float,
             first: bool) -> tuple[dict[str, Any], str]:
    """Execute one DSH turn for `task`, persisting state as events arrive.

    Returns (task, reply).  `task["status"]` always reflects the outcome and the
    caller only reports success when the status says so.  The backend is fixed
    for the whole task: a Desktop task never silently falls back to headless.
    """
    store = ctx.store
    task_id = str(task["id"])
    workspace = str(task["workspace"])
    backend = task_backend(task)
    logs = store.logs(task_id)

    events = LogWriter(Path(logs["events_jsonl"]))
    conversation = ConversationLog(Path(logs["conversation_md"]))
    run_id = uuid.uuid4().hex[:8]
    round_no = int(task.get("rounds") or 0) + 1

    task["status"] = STATUS_RUNNING
    task["rounds"] = round_no
    task["last_error"] = None
    task["backend"] = backend
    store.save(task)

    conversation.add("GPT REQUEST", message, round_no)
    # Progress goes to stderr so a long run can be watched; stdout carries the
    # single final JSON object.
    print(
        f"[dsh-collab] task {task_id} round {round_no} backend {backend} "
        f"workspace {workspace}\n"
        f"[dsh-collab] conversation log: {logs['conversation_md']}",
        file=sys.stderr, flush=True,
    )

    def on_event(event: dict[str, Any]) -> None:
        events.append_record({
            "ts": utc_now(),
            "run": run_id,
            "round": round_no,
            "source": "dsh",
            # Reasoning text is elided here: this file is user-readable.
            "event": redact_event(event),
        })

    def on_session(sid: str) -> None:
        # Persist the session id the moment the session event arrives.
        task["session_id"] = sid
        store.save(task)
        events.append_record({
            "ts": utc_now(),
            "run": run_id,
            "round": round_no,
            "source": "lifecycle",
            "lifecycle": "session_persisted",
            "session_id": sid,
        })

    def on_diag(text: str) -> None:
        events.append_record({
            "ts": utc_now(),
            "run": run_id,
            "round": round_no,
            "source": "diagnostic",
            "message": text,
        })
        conversation.add("DIAGNOSTIC", text, round_no)

    events.append_record({
        "ts": utc_now(),
        "run": run_id,
        "round": round_no,
        "source": "lifecycle",
        "lifecycle": "run_start",
        "backend": backend,
        "workspace": workspace,
        "resumed_session": task.get("session_id"),
        "first_turn": first,
    })

    reply = ""
    # Launch inside the authorised workspace, never inside the log directory.
    try:
        if backend == BACKEND_DESKTOP:
            create = None
            if not task.get("session_id"):
                create = {"workspace": workspace, "title": task.get("title")}
            runner = ctx.desktop_runner(
                workspace, timeout, on_event=on_event, on_session=on_session,
                on_diag=on_diag, session_id=task.get("session_id"), create=create)
            result = runner.run(task.get("session_id"), _prepare_run(
                task, workspace, message, first=first))
        else:
            runner = ctx.runner(workspace, timeout, on_event=on_event,
                                on_session=on_session, on_diag=on_diag)
            result = runner.run(task.get("session_id"), _prepare_run(
                task, workspace, message, first=first))
    except BaseException as exc:  # never lose the failure from the logs
        task["status"] = STATUS_FAILED
        task["last_error"] = f"runner crashed: {type(exc).__name__}: {exc}"
        store.save(task)
        events.append_record({
            "ts": utc_now(), "run": run_id, "round": round_no,
            "source": "lifecycle", "lifecycle": "error",
            "error": task["last_error"],
        })
        conversation.add("ERROR", task["last_error"], round_no)
        events.close()
        conversation.close()
        raise

    if result.session_id:
        task["session_id"] = result.session_id
    if getattr(result, "workspace_id", None):
        task["workspace_id"] = result.workspace_id
    if getattr(result, "actual_model", None):
        task["actual_model"] = result.actual_model
    if getattr(result, "request_id", None):
        task["last_request_id"] = result.request_id
    reply = result.reply
    classification = classify_reply(result.final_text if result.final_seen else "")
    result.classification = classification
    task["classification"] = classification
    task["last_classification"] = classification

    if result.ok:
        task["status"] = status_for_classification(classification)
        task["last_error"] = None
    else:
        task["status"] = STATUS_INTERRUPTED if result.interrupted else STATUS_FAILED
        task["last_error"] = result.error or "dsh run failed"
        if not result.error:
            result.error = task["last_error"]

    if reply:
        conversation.add("DSH REPLY", reply, round_no)
    # Any non-success must leave a concrete reason in the human log.
    if task["status"] in (STATUS_FAILED, STATUS_INTERRUPTED) and task["last_error"]:
        conversation.add("ERROR", task["last_error"], round_no)
    if result.session_mismatch:
        conversation.add("SESSION MISMATCH", result.session_mismatch, round_no)
    if result.kill_info:
        conversation.add("TERMINATION", json.dumps(result.kill_info, ensure_ascii=False),
                         round_no)
    cancel_info = getattr(result, "cancel_info", None)
    if cancel_info:
        conversation.add("CANCELLATION", json.dumps(cancel_info, ensure_ascii=False),
                         round_no)

    events.append_record({
        "ts": utc_now(),
        "run": run_id,
        "round": round_no,
        "source": "lifecycle",
        "lifecycle": "run_end",
        "ok": result.ok,
        "backend": backend,
        "status": task["status"],
        "classification": classification,
        "returncode": result.returncode,
        "timed_out": result.timed_out,
        "interrupted": result.interrupted,
        "final_seen": result.final_seen,
        "events": result.event_count,
        "event_types": result.event_types,
        "invalid_lines": result.bad_lines,
        "session_id": task.get("session_id"),
        "workspace_id": task.get("workspace_id"),
        "selected_model": task.get("selected_model"),
        "actual_model": task.get("actual_model"),
        "session_mismatch": result.session_mismatch,
        "error": task.get("last_error"),
        "kill": result.kill_info,
        "cancel": cancel_info,
        "turn_reason": getattr(result, "turn_reason", None),
        "reply_chars": len(reply),
    })
    store.save(task)
    events.close()
    conversation.close()
    return task, reply


