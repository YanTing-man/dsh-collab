def add_command(sub: Any, name: str, help_text: str) -> argparse.ArgumentParser:
    """Register a subcommand and record its own name on the namespace.

    The name travels with the parsed args, so every JSON summary can report the
    command that actually ran instead of a placeholder.
    """
    parser = sub.add_parser(name, help=help_text)
    parser.set_defaults(command=name)
    return parser


