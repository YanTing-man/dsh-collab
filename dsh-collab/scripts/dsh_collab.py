def resolve_dsh_cmd(args: argparse.Namespace) -> tuple[str, str]:
    """Resolve the executable and report which source actually won.

    Precedence: `--dsh-cmd`, then `$DSH_CMD`, then the built-in default.  Only a
    path is ever accepted.  The source label is returned so `doctor` can report
    provenance truthfully instead of guessing from the environment.
    """
    if args.dsh_cmd:
        return args.dsh_cmd, "argument"
    env = os.environ.get("DSH_CMD")
    if env:
        return env, "env"
    return DEFAULT_DSH_CMD, "default"


def resolve_electron_exe(args: argparse.Namespace) -> str:
    """Resolve the Electron binary; only a plain existing path is accepted."""
    explicit = getattr(args, "electron_exe", None)
    if explicit:
        return validate_executable_path(explicit, "--electron-exe", (".exe",))
    env = os.environ.get("DSH_DESKTOP_EXECUTABLE")
    if env:
        return validate_executable_path(env, "DSH_DESKTOP_EXECUTABLE", (".exe",))
    return DEFAULT_ELECTRON_EXE


def main(argv: Sequence[str] | None = None,
         runner_factory: Callable[..., DshRunner] | None = None,
         spawn: Callable[..., subprocess.Popen] | None = None,
         argv_prefix: Sequence[str] | None = None,
         stdout: Any = None,
         desktop_runner_factory: Callable[..., DesktopRunner] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    parser = build_parser()
    args = parser.parse_args(argv)
    out = stdout or sys.stdout

    def fail(message: str, code: int) -> int:
        emit({"ok": False, "command": args.subcommand, "error": message}, stdout=out)
        return code

    # Validate the executable overrides before touching the filesystem, so a bad
    # path never creates directories or reports an unrelated failure.
    try:
        dsh_cmd, dsh_source = resolve_dsh_cmd(args)
        if args.dsh_cmd or os.environ.get("DSH_CMD"):
            # An explicit override must be a plain executable path, never extra
            # shell arguments.
            validate_dsh_cmd(dsh_cmd)
        electron_exe = resolve_electron_exe(args)
    except UsageError as exc:
        return fail(str(exc), EXIT_USAGE)

    store = TaskStore(resolve_state_root(args.state_root))
    desktop_endpoint = resolve_desktop_endpoint(store.root, args.desktop_endpoint)
    ctx = Context(store, dsh_cmd, runner_factory=runner_factory,
                  spawn=spawn, argv_prefix=argv_prefix,
                  dsh_cmd_source=dsh_source, stdout=out,
                  desktop_endpoint=desktop_endpoint,
                  electron_exe=electron_exe,
                  desktop_runner_factory=desktop_runner_factory)

    handler = COMMANDS[args.subcommand]
    try:
        payload = handler(ctx, args)
    except UsageError as exc:
        return fail(str(exc), EXIT_USAGE)
    except TaskError as exc:
        return fail(str(exc), EXIT_FAIL)
    except KeyboardInterrupt:
        return fail("interrupted by user", EXIT_FAIL)
    except Exception as exc:  # unexpected: still machine-readable
        return fail(f"{type(exc).__name__}: {exc}", EXIT_FAIL)

    payload.setdefault("command", args.subcommand)
    emit(payload, stdout=out)
    return EXIT_OK if payload.get("ok") else EXIT_FAIL


def cli() -> int:
    """Console entrypoint: UTF-8 streams, then the argument parser."""
    configure_stdio()
    return main()


if __name__ == "__main__":
    raise SystemExit(cli())
