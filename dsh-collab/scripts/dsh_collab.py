if os.name == "nt":  # pragma: no cover - exercised on Windows CI
    import msvcrt

    def _lock_file(fh: Any) -> None:
        # LK_NBLCK fails immediately when another process holds the lock; we do
        # not want `send`/`review` to sit and wait behind a long DSH run.
        fh.seek(0)
        msvcrt.locking(fh.fileno(), msvcrt.LK_NBLCK, 1)

    def _unlock_file(fh: Any) -> None:
        with contextlib.suppress(OSError):
            fh.seek(0)
            msvcrt.locking(fh.fileno(), msvcrt.LK_UNLCK, 1)
else:  # pragma: no cover - POSIX
    import fcntl

    def _lock_file(fh: Any) -> None:
        fcntl.flock(fh.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)

    def _unlock_file(fh: Any) -> None:
        with contextlib.suppress(OSError):
            fcntl.flock(fh.fileno(), fcntl.LOCK_UN)


class TaskLock:
    """Exclusive per-task lock, failing fast when another run holds it.

    The lock lives on an OS file handle, so it is released automatically if the
    holder crashes; nothing on disk needs cleaning up afterwards.
    """

    def __init__(self, path: Path):
        self.path = path
        self._fh: Any = None

    def acquire(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        fh = open(self.path, "a+b")
        try:
            # Windows cannot lock a zero-length region, so guarantee one byte.
            if os.fstat(fh.fileno()).st_size == 0:
                fh.write(b"\0")
                fh.flush()
            _lock_file(fh)
        except OSError as exc:
            fh.close()
            raise TaskError(
                f"task is busy: another send/review holds {self.path} "
                f"({exc}); wait for it to finish or investigate a stale run"
            ) from exc
        with contextlib.suppress(Exception):
            fh.seek(0, os.SEEK_END)
            fh.write(f"{os.getpid()}\n".encode("ascii", "replace"))
            fh.flush()
        self._fh = fh

    def release(self) -> None:
        if self._fh is not None:
            _unlock_file(self._fh)
            with contextlib.suppress(Exception):
                self._fh.close()
            self._fh = None

    def __enter__(self) -> "TaskLock":
        self.acquire()
        return self

    def __exit__(self, *exc: Any) -> None:
        self.release()


