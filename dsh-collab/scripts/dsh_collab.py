def desktop_helper_argv(electron_exe: str, helper: Path | str,
                        endpoint_file: Path | str, command: str) -> list[str]:
    """`<electron> <helper.cjs> <endpoint.json> <command>`.

    The command's parameters travel on stdin, so no task text, title or
    credential ever reaches this argument vector.
    """
    return [str(electron_exe), str(helper), str(endpoint_file), command]


class DesktopHelperCall:
    """Outcome of one one-shot helper invocation (models/prepare/select-model)."""

    def __init__(self) -> None:
        self.command: str = ""
        self.returncode: int | None = None
        self.timed_out: bool = False
        self.events: list[dict[str, Any]] = []
        self.result: Any = None
        self.error: str | None = None
        self.error_code: str | None = None
        self.stderr_tail: str = ""
        self.workspace_id: str | None = None
        self.session_id: str | None = None

    def absorb(self, event: dict[str, Any]) -> None:
        etype = str(event.get("type", ""))
        if etype == "result":
            self.result = event.get("value")
        elif etype == "error":
            self.error = str(event.get("message") or "the Desktop helper failed")
            self.error_code = str(event.get("code") or "error")
        elif etype == "workspace" and isinstance(event.get("workspaceId"), str):
            self.workspace_id = event["workspaceId"]
        elif etype == "session" and isinstance(event.get("sessionId"), str):
            self.session_id = event["sessionId"]


def _drain_stdout_lines(stream: Any, sink: Callable[[str], None]) -> None:
    try:
        for raw_line in iter(stream.readline, b""):
            text = _decode(raw_line).strip()
            if text:
                sink(text)
    except (OSError, ValueError):
        pass
    finally:
        with contextlib.suppress(Exception):
            stream.close()


def _drain_stderr(stream: Any, call: Any) -> None:
    try:
        for raw_line in iter(stream.readline, b""):
            text = _decode(raw_line)
            call.stderr_tail = (call.stderr_tail + text)[-4000:]
    except (OSError, ValueError):
        pass
    finally:
        with contextlib.suppress(Exception):
            stream.close()


def parse_helper_event(line: str, call: Any) -> None:
    """Parse one helper NDJSON line into `call`; malformed lines are diagnosed."""
    try:
        event = json.loads(line)
    except json.JSONDecodeError as exc:
        call.events.append({"_invalid": True, "_error": exc.msg})
        return
    if not isinstance(event, dict):
        call.events.append({"_invalid": True, "_error": "event is not a JSON object"})
        return
    call.events.append(event)
    call.absorb(event)


def invoke_desktop_helper(electron_exe: str, helper: Path | str, endpoint_file: Path | str,
                          command: str, payload: dict[str, Any] | None, *,
                          cwd: str, timeout: float,
                          spawn: Callable[..., subprocess.Popen] | None = None,
                          env: dict[str, str] | None = None) -> DesktopHelperCall:
    """Run one one-shot Desktop helper command and collect its NDJSON events.

    The payload (which may contain a task title or model selection) goes to the
    helper's stdin and never into argv.  Only the helper process is ever
    terminated here; the Desktop process is not ours to kill.
    """
    call = DesktopHelperCall()
    call.command = command
    argv = desktop_helper_argv(electron_exe, helper, endpoint_file, command)
    body = json.dumps(payload if payload is not None else {}, ensure_ascii=False) + "\n"
    popen = spawn or subprocess.Popen
    popen_kwargs: dict[str, Any] = {
        "cwd": cwd,
        "stdin": subprocess.PIPE,
        "stdout": subprocess.PIPE,
        "stderr": subprocess.PIPE,
        "env": desktop_helper_env(env),
    }
    if os.name == "nt":
        popen_kwargs["creationflags"] = getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)
    else:
        popen_kwargs["start_new_session"] = True
    proc = popen(argv, **popen_kwargs)
    readers: list[threading.Thread] = []
    try:
        if proc.stdout is None or proc.stderr is None:
            raise TaskError("the Desktop helper pipes were not created")
        out_thread = threading.Thread(
            target=_drain_stdout_lines,
            args=(proc.stdout, lambda line: parse_helper_event(line, call)),
            daemon=True)
        err_thread = threading.Thread(target=_drain_stderr, args=(proc.stderr, call), daemon=True)
        out_thread.start()
        err_thread.start()
        readers = [out_thread, err_thread]
        try:
            if proc.stdin is not None:
                proc.stdin.write(body.encode("utf-8"))
                proc.stdin.flush()
        except (OSError, ValueError) as exc:
            call.error = call.error or f"could not deliver the Desktop request over stdin: {exc}"
        finally:
            with contextlib.suppress(Exception):
                if proc.stdin is not None:
                    proc.stdin.close()
        try:
            call.returncode = proc.wait(timeout=max(0.0, float(timeout)))
        except subprocess.TimeoutExpired:
            call.timed_out = True
            call.error = call.error or f"the Desktop helper timed out after {timeout:g}s"
            with contextlib.suppress(Exception):
                proc.kill()
            with contextlib.suppress(Exception):
                proc.wait(timeout=5)
    finally:
        for thread in readers:
            thread.join(timeout=5.0)
        if proc.poll() is None:
            with contextlib.suppress(Exception):
                proc.kill()
    if call.error is None and not call.timed_out and call.returncode != 0:
        tail = call.stderr_tail.strip()[-300:]
        call.error = f"the Desktop helper exited with code {call.returncode}"
        if tail:
            call.error += f": {tail}"
    return call


class DesktopRunner:
    """Runs one turn inside a live Desktop session.

    Mirrors `DshRunner`'s contract (same `TurnResult`, same callbacks) so the
    rest of the bridge does not care which backend produced the turn, but the
    transport is completely different: the helper talks to the running Desktop
    over its authenticated loopback API.  On timeout the bridge asks the Desktop
    Host to cancel the session and reports the outcome; the helper process is
    disposable, the Desktop process never is.
    """

    def __init__(self, electron_exe: str, helper: Path | str, endpoint_file: Path | str,
                 cwd: str, timeout: float,
                 on_event: Callable[[dict[str, Any]], None] | None = None,
                 on_session: Callable[[str], None] | None = None,
                 on_diag: Callable[[str], None] | None = None,
                 spawn: Callable[..., subprocess.Popen] | None = None,
                 session_id: str | None = None,
                 create: dict[str, Any] | None = None,
                 request_id: str | None = None,
                 client_time_zone: str = DESKTOP_CLIENT_TIME_ZONE,
                 cancel_grace: float = DESKTOP_CANCEL_GRACE,
                 cancel_lock_timeout: float = DESKTOP_CANCEL_LOCK_TIMEOUT,
                 env: dict[str, str] | None = None):
        self.electron_exe = electron_exe
        self.helper = Path(helper)
        self.endpoint_file = str(endpoint_file)
        self.cwd = cwd
        self.timeout = float(timeout)
        self.on_event = on_event
        self.on_session = on_session
        self.on_diag = on_diag
        self._spawn = spawn or subprocess.Popen
        self.session_id = session_id
        self.create = create
        self.request_id = request_id or uuid.uuid4().hex
        self.client_time_zone = client_time_zone
        self.cancel_grace = float(cancel_grace)
        self.cancel_lock_timeout = float(cancel_lock_timeout)
        self.env = env

    # -- internals ---------------------------------------------------------

    def _diag(self, message: str) -> None:
        if self.on_diag is not None:
            self.on_diag(message)

    def _emit(self, event: dict[str, Any]) -> None:
        if self.on_event is not None:
            self.on_event(event)

    def _handle_line(self, raw: str, result: TurnResult) -> None:
        raw = raw.strip()
        if not raw:
            return
        try:
            event = json.loads(raw)
        except json.JSONDecodeError as exc:
            result.bad_lines += 1
            self._diag(f"unparseable NDJSON line ({exc.msg}): {raw[:300]}")
            self._emit({"_invalid": True, "_error": exc.msg})
            return
        if not isinstance(event, dict):
            result.bad_lines += 1
            self._diag(f"non-object NDJSON event: {raw[:300]}")
            self._emit({"_invalid": True, "_error": "event is not a JSON object"})
            return

        result.event_count += 1
        etype = str(event.get("type", "unknown"))
        result.event_types[etype] = result.event_types.get(etype, 0) + 1
        self._emit(event)

        if etype == "workspace":
            workspace_id = event.get("workspaceId")
            if isinstance(workspace_id, str) and workspace_id:
                result.workspace_id = workspace_id
            return
        if etype == "header":
            result.actual_model = {
                "provider": event.get("provider"),
                "model": event.get("model"),
                "reasoningEffort": event.get("reasoningEffort"),
            }
            return
        if etype == "turn_end":
            reason = event.get("reason")
            if isinstance(reason, dict):
                result.turn_reason = reason
            return
        if etype == "approval":
            self._diag(
                "the Desktop session is waiting for an approval; approve or deny it "
                f"in the Desktop window (tool {event.get('toolName')!r})"
            )
            return
        if etype == "cancel":
            # `stopped` is the only field that may claim the turn really ended.
            # Anything else (a missing field, or `ok` without `stopped`) means
            # the request was delivered and the outcome is unconfirmed.
            result.cancel_info = {
                "requested": bool(event.get("requested")),
                "ok": bool(event.get("ok")),
                "stopped": event.get("stopped") is True,
                "detail": str(event.get("detail") or ""),
            }
            return
        if etype == "error":
            message = str(event.get("message") or "the Desktop helper reported an error")
            result.error = result.error or message
            self._diag(message)
            return
        if etype == "result":
            return

        before_session = result.session_id
        apply_protocol_event(result, event, self._diag)
        if result.session_id is not None and before_session is None:
            if self.on_session is not None:
                self.on_session(result.session_id)

    def _drain(self, stream: Any, result: TurnResult, is_stderr: bool) -> None:
        try:
            for raw_line in iter(stream.readline, b""):
                text = _decode(raw_line)
                if is_stderr:
                    result.stderr_tail = (result.stderr_tail + text)[-4000:]
                    self._diag(f"stderr: {text.rstrip()}")
                else:
                    self._handle_line(text, result)
        except (OSError, ValueError) as exc:
            if result.reader_error is None:
                result.reader_error = f"failed reading the Desktop helper output: {exc}"
        except Exception as exc:  # unexpected: never swallow silently
            if result.reader_error is None:
                result.reader_error = f"{type(exc).__name__}: {exc}"
        finally:
            with contextlib.suppress(Exception):
                stream.close()

    def _request_body(self, task_text: str) -> bytes:
        request: dict[str, Any] = {
            "cmd": "turn",
            "text": task_text,
            "requestId": self.request_id,
            "clientTimeZone": self.client_time_zone,
        }
        if self.session_id:
            request["sessionId"] = self.session_id
        if self.create:
            request["create"] = {
                "workspace": self.create.get("workspace"),
                "title": self.create.get("title"),
            }
        return (json.dumps(request, ensure_ascii=False) + "\n").encode("utf-8")

    # -- public ------------------------------------------------------------

    def run(self, session_id: str | None, task_text: str) -> TurnResult:
        result = TurnResult()
        result.expected_session_id = session_id
        result.request_id = self.request_id
        if session_id:
            self.session_id = session_id
        argv = desktop_helper_argv(self.electron_exe, self.helper, self.endpoint_file, "turn")

        popen_kwargs: dict[str, Any] = {
            "cwd": self.cwd,
            "stdin": subprocess.PIPE,
            "stdout": subprocess.PIPE,
            "stderr": subprocess.PIPE,
            "env": desktop_helper_env(self.env),
        }
        if os.name == "nt":
            popen_kwargs["creationflags"] = getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)
        else:
            popen_kwargs["start_new_session"] = True

        proc = self._spawn(argv, **popen_kwargs)
        readers: list[threading.Thread] = []
        cancel_result: dict[str, Any] = {
            "requested": False, "ok": False, "stopped": False, "detail": "",
        }
        deadline = time.monotonic() + self.timeout
        # Defined before `request_cancel` because the timeout path uses both.
        stdin_done = threading.Event()
        stdin_lock = threading.Lock()

        def request_cancel(reason: str) -> None:
            """Ask the helper to cancel without ever waiting on the stdin lock.

            The writer holds that lock while it pushes the task text, which can
            be arbitrarily large.  Blocking here would stall the timeout path
            behind it, so a lock that is not free within the grace period is a
            hard, reported failure: the cancel frame was never delivered and
            nothing may claim the turn stopped.
            """
            if proc.stdin is None:
                cancel_result["detail"] = (
                    cancel_result["detail"] or "no stdin pipe to ask the helper to cancel"
                )
                return
            if not stdin_lock.acquire(timeout=self.cancel_lock_timeout):
                cancel_result["detail"] = (
                    f"could not ask the helper to cancel ({reason}): the task-input "
                    "writer still holds the stdin lock after "
                    f"{self.cancel_lock_timeout:g}s, so the cancel request was never "
                    "delivered and the turn is unconfirmed"
                )
                return
            try:
                proc.stdin.write(b'{"cmd":"cancel"}\n')
                proc.stdin.flush()
                cancel_result["requested"] = True
            except (OSError, ValueError) as exc:
                cancel_result["detail"] = (
                    f"could not ask the helper to cancel ({reason}): {exc}"
                )
            finally:
                stdin_lock.release()
        try:
            if proc.stdout is None or proc.stderr is None:
                raise TaskError("the Desktop helper pipes were not created")
            for stream, is_err in ((proc.stdout, False), (proc.stderr, True)):
                thread = threading.Thread(target=self._drain, args=(stream, result, is_err), daemon=True)
                thread.start()
                readers.append(thread)

            body = self._request_body(task_text)

            def deliver() -> None:
                try:
                    if proc.stdin is not None:
                        with stdin_lock:
                            proc.stdin.write(body)
                            proc.stdin.flush()
                except (OSError, ValueError) as exc:
                    result.stdin_error = f"could not deliver the task text over stdin: {exc}"
                finally:
                    stdin_done.set()

            if proc.stdin is not None:
                writer = threading.Thread(target=deliver, daemon=True)
                writer.start()

            try:
                result.returncode = proc.wait(timeout=max(0.0, deadline - time.monotonic()))
            except subprocess.TimeoutExpired:
                result.timed_out = True
                # Ask the Host to cancel the session.  Killing the Desktop
                # process would be destructive and is never an option; the
                # helper is only a client.
                request_cancel("timeout")
                try:
                    result.returncode = proc.wait(timeout=self.cancel_grace)
                except subprocess.TimeoutExpired:
                    result.returncode = None
                    cancel_result["detail"] = (
                        cancel_result["detail"]
                        or "the Desktop helper did not report a cancellation within "
                           f"{self.cancel_grace:g}s"
                    )
                if proc.poll() is None:
                    # Only the helper is terminated; the Desktop keeps running.
                    result.kill_info = terminate_process_tree(proc.pid)
            except KeyboardInterrupt:
                result.interrupted = True
                result.error = "interrupted by user"
                request_cancel("interrupt")
                try:
                    result.returncode = proc.wait(timeout=self.cancel_grace)
                except subprocess.TimeoutExpired:
                    result.returncode = None
            finally:
                if not stdin_done.wait(timeout=5.0) and result.stdin_error is None:
                    result.stdin_error = "task input writer did not finish"
        except BaseException:
            with contextlib.suppress(Exception):
                if proc.poll() is None:
                    proc.kill()
            raise
        finally:
            for thread in readers:
                thread.join(timeout=10.0)
            for thread in readers:
                if thread.is_alive():
                    result.readers_hung = True
            with contextlib.suppress(Exception):
                if proc.stdin is not None:
                    proc.stdin.close()
            if proc.poll() is None:  # defensive: never leave a helper orphan
                with contextlib.suppress(Exception):
                    proc.kill()

        if result.cancel_info is None and (cancel_result["requested"] or result.timed_out):
            # No cancel event arrived from the helper: the request was sent (or
            # never delivered), and nothing here may claim the turn stopped.
            result.cancel_info = dict(cancel_result)
        elif result.cancel_info is not None and cancel_result["detail"] and not result.cancel_info.get("detail"):
            result.cancel_info["detail"] = cancel_result["detail"]
        if result.returncode == DESKTOP_HELPER_EXIT_CANCELLED and result.error is None:
            result.error = "the Desktop turn was cancelled before it completed"
        self._finalize(result)
        return result

    def _finalize(self, result: TurnResult) -> None:
        """Decide the turn outcome from the helper's exit code plus its events."""
        if result.timed_out or result.interrupted:
            cause = "interrupted by user" if result.interrupted else f"timeout after {self.timeout:g}s"
            detail = ""
            cancel = result.cancel_info or {}
            if result.cancel_info is not None:
                detail = str(cancel.get("detail") or "")
            if cancel.get("stopped") is True:
                # The helper confirmed the session stopped; only then may the
                # report claim the turn is over.
                result.error = (
                    f"{cause}; Desktop confirmed the session "
                    "cancel and reported the turn stopped"
                )
            elif cancel.get("requested") or cancel.get("ok"):
                result.error = (
                    f"{cause}; a session/cancel was requested "
                    "from Desktop but its stop was not confirmed, so the turn may "
                    "still be running"
                    + (f" ({detail})" if detail else "")
                    + " - check the Desktop window"
                )
            else:
                result.error = (
                    f"{cause}; no cancel could be delivered, "
                    "so the Desktop task is unconfirmed and may still be running"
                    + (f" ({detail})" if detail else "")
                    + " - check the Desktop window"
                )
            return
        if result.stdin_error and result.error is None:
            result.error = result.stdin_error
            return
        if result.reader_error and result.error is None:
            result.error = result.reader_error
            return
        if result.returncode == DESKTOP_HELPER_EXIT_CANCELLED:
            result.error = result.error or (
                "the Desktop turn was cancelled before it completed"
            )
            return
        if result.returncode is None:
            result.error = result.error or "the Desktop helper did not report an exit code"
            return
        if result.returncode != 0:
            if result.error is None:
                tail = result.stderr_tail.strip()[-400:]
                result.error = f"the Desktop helper exited with code {result.returncode}"
                if tail:
                    result.error += f": {tail}"
            return
        if not result.session_id:
            result.error = result.error or (
                "the Desktop turn produced no session id; session not established")
            return
        if not result.final_seen:
            result.error = (
                "the Desktop turn ended without a final event; the turn did not "
                "complete (stderr tail: "
                f"{result.stderr_tail.strip()[-200:] or 'empty'})"
            )
            return
        if not result.reply:
            result.error = "the Desktop final event contained no usable reply"
            return
        if result.readers_hung:
            result.error = (
                "the Desktop helper output readers did not finish after the process "
                "exited; refusing to treat the turn as complete"
            )


