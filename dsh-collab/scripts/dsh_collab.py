def _mkstemp_beside(path: Path) -> tuple[int, str]:
    """Create a unique temp file in the target's own directory.

    `tempfile.mkstemp` is tried first, but a confined sandbox can point the temp
    root somewhere unwritable while the target directory is fine, so a sibling
    file is the fallback.  Either way the temp file is on the same volume as the
    target, which is what makes `os.replace` atomic.
    """
    try:
        return tempfile.mkstemp(dir=str(path.parent), prefix=".tmp-", suffix=".json")
    except OSError:
        pass
    for _ in range(10):
        candidate = path.parent / f".tmp-{os.getpid()}-{uuid.uuid4().hex[:8]}.json"
        try:
            fd = os.open(candidate, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        except FileExistsError:
            continue
        return fd, str(candidate)
    raise OSError(f"could not create a temporary file next to {path}")


def atomic_write_text(path: Path, text: str) -> None:
    """Write via a same-directory temp file + os.replace (atomic on Windows).

    A reader (or a crash) therefore never observes a half-written `task.json`.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = _mkstemp_beside(path)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise


class LogWriter:
    """Append-only, immediately-flushed text log so a human can `tail` it.

    All writes for a task funnel through here, guarded by a re-entrant lock: the
    reader thread appends raw NDJSON while the main thread appends lifecycle and
    conversation records.
    """

    def __init__(self, path: Path):
        self.path = path
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self._lock = threading.RLock()
        self._fh = open(self.path, "a", encoding="utf-8", newline="\n")

    def write_raw(self, text: str) -> None:
        with self._lock:
            if not text.endswith("\n"):
                text += "\n"
            self._fh.write(text)
            self._fh.flush()

    def append_record(self, record: dict[str, Any]) -> None:
        self.write_raw(json.dumps(record, ensure_ascii=False))

    def close(self) -> None:
        with self._lock:
            with contextlib.suppress(Exception):
                self._fh.flush()
            with contextlib.suppress(Exception):
                self._fh.close()


class ConversationLog:
    """Human-readable, timestamped narrative.  Never private chain of thought."""

    def __init__(self, path: Path):
        self.path = path
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self._lock = threading.RLock()
        if not self.path.exists():
            self.path.write_text(
                "# dsh-collab conversation\n\n"
                "GPT requests, DSH replies, reviewer evidence/verdicts and errors.\n",
                encoding="utf-8",
            )
        self._fh = open(self.path, "a", encoding="utf-8", newline="\n")

    def add(self, kind: str, body: str, round_no: int | None = None) -> None:
        body = (body or "").replace("\r\n", "\n").replace("\r", "\n").rstrip("\n")
        if not body:
            body = "(empty)"
        where = f", round {round_no}" if round_no is not None else ""
        header = f"\n## [{utc_now()}] {kind}{where}\n\n"
        with self._lock:
            self._fh.write(header + body + "\n")
            self._fh.flush()

    def close(self) -> None:
        with self._lock:
            with contextlib.suppress(Exception):
                self._fh.close()


