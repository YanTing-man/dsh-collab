def read_desktop_descriptor(path: Path) -> dict[str, Any]:
    """Read the private descriptor WITHOUT ever returning its launch token.

    Only the fields the bridge may report or need are surfaced; the
    authenticated URL is reduced to host/port facts.  Callers must never print
    the raw file.
    """
    try:
        raw = Path(path).read_text(encoding="utf-8")
    except OSError as exc:
        raise TaskError(f"Desktop endpoint descriptor is unreadable ({path}): {exc}") from exc
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise TaskError(f"Desktop endpoint descriptor is not valid JSON ({path}): {exc}") from exc
    if not isinstance(data, dict):
        raise TaskError(f"Desktop endpoint descriptor is not a JSON object ({path})")
    url_raw = data.get("authenticatedUrl")
    host = None
    port = None
    has_token = False
    if isinstance(url_raw, str) and url_raw:
        try:
            parsed = urlparse(url_raw)
        except ValueError:
            parsed = None
        if parsed is not None:
            host = parsed.hostname
            port = parsed.port
            has_token = bool(parsed.query)
    return {
        "path": str(path),
        "present": True,
        "protocol": data.get("protocol"),
        "backend": data.get("backend"),
        "pid": data.get("pid") if isinstance(data.get("pid"), int) else None,
        "executable": data.get("executable") if isinstance(data.get("executable"), str) else None,
        "created_at": data.get("createdAt") if isinstance(data.get("createdAt"), str) else None,
        "host": host,
        "port": port,
        "has_launch_token": has_token,
    }


def describe_desktop_descriptor(path: Path) -> dict[str, Any]:
    """Descriptor facts for reporting; never raises and never leaks the token."""
    try:
        if not Path(path).is_file():
            return {"path": str(path), "present": False}
        return read_desktop_descriptor(path)
    except TaskError as exc:
        return {"path": str(path), "present": True, "error": str(exc)}



