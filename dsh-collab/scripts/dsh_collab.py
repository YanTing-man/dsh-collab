class TaskStore:
    """Filesystem layout for tasks.

        <root>/<task-id>/task.json
        <root>/<task-id>/conversation.md
        <root>/<task-id>/events.jsonl
        <root>/<task-id>/task.lock

    Construction never raises: read-only commands such as `doctor` and `list`
    must still work when the state root does not exist or is not writable.
    """

    def __init__(self, root: Path):
        self.root = Path(root)
        # Best-effort: record a failure rather than crashing the whole CLI.
        self.init_error: str | None = None
        try:
            self.root.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            self.init_error = f"cannot create state root {self.root}: {exc}"

    def ensure(self) -> None:
        """Require a usable state root, for commands that write."""
        if self.init_error is not None:
            raise TaskError(self.init_error)
        try:
            self.root.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            self.init_error = f"cannot create state root {self.root}: {exc}"
            raise TaskError(self.init_error) from exc

    @property
    def writable(self) -> bool:
        if self.init_error is not None or not self.root.is_dir():
            return False
        return os.access(self.root, os.W_OK)

    def task_dir(self, task_id: str) -> Path:
        return self.root / validate_task_id(task_id)

    def load(self, task_id: str) -> dict[str, Any]:
        path = self.task_dir(task_id) / "task.json"
        if not path.is_file():
            raise TaskError(f"unknown task: {task_id}")
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise TaskError(f"task {task_id} metadata is unreadable: {exc}") from exc
        if not isinstance(data, dict):
            raise TaskError(f"task {task_id} metadata is not a JSON object")
        return data

    def save(self, task: dict[str, Any]) -> None:
        task_id = validate_task_id(str(task["id"]))
        task["updated_at"] = utc_now()
        path = self.task_dir(task_id) / "task.json"
        atomic_write_text(path, json.dumps(task, ensure_ascii=False, indent=2) + "\n")

    def exists(self, task_id: str) -> bool:
        return (self.task_dir(task_id) / "task.json").is_file()

    def lock(self, task_id: str) -> TaskLock:
        return TaskLock(self.task_dir(task_id) / "task.lock")

    def logs(self, task_id: str) -> dict[str, str]:
        d = self.task_dir(task_id)
        return {
            "task_json": str(d / "task.json"),
            "conversation_md": str(d / "conversation.md"),
            "events_jsonl": str(d / "events.jsonl"),
        }

    def all_tasks(self) -> list[dict[str, Any]]:
        out: list[dict[str, Any]] = []
        if not self.root.is_dir():
            return out
        for child in sorted(self.root.iterdir()):
            if not child.is_dir() or not TASK_ID_RE.match(child.name):
                continue
            with contextlib.suppress(TaskError):
                out.append(self.load(child.name))
        return out


