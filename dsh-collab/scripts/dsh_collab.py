def cmd_doctor(ctx: Context, args: argparse.Namespace) -> dict[str, Any]:
    """Report availability only.  Never runs inference, never prints secrets.

    The Desktop section is informational by default (the shipped default backend
    is Desktop, but a machine without it must still get a usable headless
    report); `--require-desktop` turns its absence into a failure.
    """
    env_override = os.environ.get("DSH_CMD")
    # ctx.dsh_cmd already reflects --dsh-cmd (which outranks $DSH_CMD).
    cmd = ctx.dsh_cmd
    source_label = {
        "argument": "argument:--dsh-cmd",
        "env": "env:DSH_CMD",
        "default": "default",
    }.get(ctx.dsh_cmd_source, ctx.dsh_cmd_source)
    looks_like_path = (os.path.sep in cmd) or ("/" in cmd) or ("\\" in cmd)
    exists = Path(cmd).is_file() if looks_like_path else bool(shutil.which(cmd))

    endpoint_path = ctx.desktop_endpoint
    desktop: dict[str, Any] = {
        "endpoint_file": str(endpoint_path) if endpoint_path else None,
        "helper": str(ctx.desktop_helper),
        "helper_present": ctx.desktop_helper.is_file(),
        "electron_exe": ctx.electron_exe,
        "electron_exe_present": Path(ctx.electron_exe).is_file(),
        "default_backend": ctx.default_backend,
        "reachable": False,
    }
    if endpoint_path is not None:
        desktop.update(describe_desktop_descriptor(endpoint_path))
        pid = desktop.get("pid")
        if isinstance(pid, int) and pid > 0:
            desktop["pid_alive"] = _is_alive(pid)
    if (endpoint_path is not None and desktop.get("present")
            and not getattr(args, "no_desktop_probe", False)):
        try:
            call = ctx.desktop_invoke("doctor", {}, timeout=60.0, cwd=str(ctx.store.root))
            value = call.result if isinstance(call.result, dict) else {}
            desktop["reachable"] = bool(value.get("connected"))
            desktop["default_model"] = value.get("default")
            desktop["providers"] = value.get("providers")
            if not desktop["reachable"]:
                desktop["error"] = call.error or "the Desktop Host did not answer"
        except Exception as exc:  # a probe must never break doctor
            desktop["error"] = f"{type(exc).__name__}: {exc}"

    report = {
        "ok": True,
        "command": "doctor",
        "python": {
            "executable": sys.executable,
            "version": sys.version.split()[0],
            "supported": sys.version_info >= (3, 12),
        },
        "dsh": {
            "cmd": cmd,
            "source": source_label,
            "env_DSH_CMD_present": bool(env_override),
            "exists": bool(exists),
            "is_cmd_shim": cmd.lower().endswith((".cmd", ".bat")),
            "launch": (
                'cmd.exe /d /s /c ""<cmd>" headless --json '
                '[--session-id <validated>] -"'
            ),
            "task_text_path": "stdin (UTF-8); never argv or a command string",
        },
        "backends": {
            "default": ctx.default_backend,
            "available": [BACKEND_HEADLESS] + ([BACKEND_DESKTOP] if desktop.get("reachable") else []),
            "desktop": desktop,
        },
        "state_root": str(ctx.store.root),
        "state_root_writable": ctx.store.writable,
        "state_root_error": ctx.store.init_error,
        "platform": {"os": os.name, "note": "Windows-first; POSIX lock uses flock"},
        "notes": [
            "doctor performs no inference and prints no credentials",
            "only an executable path is accepted via --dsh-cmd/DSH_CMD",
            "stdin is used for all task text; nothing user-supplied enters argv",
            "the Desktop launch descriptor is never printed; only its host/port facts are",
        ],
    }
    problems: list[str] = []
    if not exists:
        problems.append(f"dsh executable not found: {cmd}")
    if not report["state_root_writable"]:
        problems.append(
            report["state_root_error"]
            or f"state root is not writable: {ctx.store.root}"
        )
    if not report["python"]["supported"]:
        problems.append("Python 3.12+ is required")
    if getattr(args, "require_desktop", False):
        if endpoint_path is None:
            problems.append("no Desktop endpoint is configured")
        elif not desktop.get("present"):
            problems.append(f"Desktop endpoint descriptor is missing: {endpoint_path}")
        elif not desktop.get("reachable"):
            problems.append(
                "the Desktop Host is not reachable"
                + (f": {desktop.get('error')}" if desktop.get("error") else
                   "; is DeepSeek Harness running?")
            )
    elif ctx.default_backend == BACKEND_DESKTOP and not desktop.get("reachable"):
        report["notes"].append(
            "the default backend is desktop but the Desktop Host is not reachable; "
            "Desktop tasks will fail loudly (they never fall back to headless) - "
            "pass --backend headless to use the CLI instead"
        )
    if problems:
        report["ok"] = False
        report["error"] = "; ".join(problems)
    return report


def validate_run_limits(timeout: float, max_rounds: int) -> None:
    """Reject unusable limits before any task directory or subprocess exists."""
    if not isinstance(timeout, (int, float)) or isinstance(timeout, bool):
        raise UsageError(f"--timeout must be a number: {timeout!r}")
    if timeout <= 0 or math.isinf(timeout) or math.isnan(timeout):
        raise UsageError(f"--timeout must be a positive finite number: {timeout!r}")
    if not isinstance(max_rounds, int) or isinstance(max_rounds, bool):
        raise UsageError(f"--max-rounds must be an integer: {max_rounds!r}")
    if max_rounds <= 0:
        raise UsageError(f"--max-rounds must be at least 1: {max_rounds!r}")


def resolve_command_backend(ctx: Context, args: argparse.Namespace,
                            task: dict[str, Any] | None = None) -> str:
    """Decide the backend for one command.

    Precedence: an explicit `--backend`, then the environment
    (`DSH_COLLAB_BACKEND`, with `DSH_COLLAB_HEADLESS=1` as the older switch),
    then the task's own recorded backend, then the default.

    For a task that already exists, an explicitly requested backend that differs
    from the task's is refused: switching mid-task would silently fork the
    conversation, so the caller must start a new task instead.  Nothing ever
    falls back to another backend after a failure.
    """
    explicit = getattr(args, "backend", None)
    if explicit is not None:
        requested = normalize_backend(explicit)
    else:
        env = os.environ.get(BACKEND_ENV)
        if env:
            requested = normalize_backend(env.strip().lower())
        elif os.environ.get(BACKEND_ENV_HEADLESS, "").strip() not in ("", "0", "false", "False"):
            requested = BACKEND_HEADLESS
        elif task is not None:
            requested = task_backend(task)
        else:
            requested = ctx.default_backend
    if task is not None:
        bound = task_backend(task)
        if requested != bound:
            raise UsageError(
                f"task {task.get('id')} is bound to the {bound!r} backend and "
                f"{requested!r} was requested; a task cannot switch backends. "
                "Start a new task with the backend you want."
            )
    return requested


def _start(ctx: Context, args: argparse.Namespace) -> dict[str, Any]:
    timeout = float(args.timeout)
    max_rounds = int(args.max_rounds)
    validate_run_limits(timeout, max_rounds)
    workspace = require_workspace(args.workspace)
    message = read_message_file(args.message_file)
    backend = resolve_command_backend(ctx, args)
    task_id = new_task_id()
    task = new_task(task_id, workspace, args.title or task_id, timeout, max_rounds,
                    backend=backend)
    store = ctx.store
    store.ensure()
    store.task_dir(task_id).mkdir(parents=True, exist_ok=True)
    store.save(task)

    with store.lock(task_id):
        try:
            task, reply = run_turn(ctx, task, message, timeout=timeout, first=True)
        except BaseException as exc:
            return summary(task, store, ok=False, command="start",
                           error=f"runner crashed: {type(exc).__name__}: {exc}")

    return _turn_summary(task, store, reply, "start")


def _prepare(ctx: Context, args: argparse.Namespace) -> dict[str, Any]:
    """Create an empty Desktop session for a task explicitly pinned to a model.

    Use this only when the user asks for a first-round model/effort choice: it
    registers the workspace, creates the session, names it, and stops, so a
    `select-model` can be applied before the first `send`.  The first `send`
    then injects the turn-1 brief.  For an ordinary task, call `start` directly
    and let Desktop keep its own default; do not stop to ask.

    Two honest limits: a session that never ran a turn is hidden by the Desktop
    sidebar, so it cannot be "seen there before it starts" (`--task` is the only
    handle); and no model runs here, so nothing can be read back from it.
    """
    timeout = float(args.timeout)
    max_rounds = int(args.max_rounds)
    validate_run_limits(timeout, max_rounds)
    workspace = require_workspace(args.workspace)
    backend = resolve_command_backend(ctx, args)
    if backend != BACKEND_DESKTOP:
        raise UsageError(
            "prepare is a Desktop-only command: a headless session is created by "
            "`start`, which also runs turn 1"
        )
    store = ctx.store
    store.ensure()
    task_id = new_task_id()
    title = args.title or task_id
    task = new_task(task_id, workspace, title, timeout, max_rounds, backend=backend)
    store.task_dir(task_id).mkdir(parents=True, exist_ok=True)
    store.save(task)

    with store.lock(task_id):
        conversation = ConversationLog(Path(store.logs(task_id)["conversation_md"]))
        events = LogWriter(Path(store.logs(task_id)["events_jsonl"]))
        call: DesktopHelperCall | None = None
        try:
            try:
                call = ctx.desktop_invoke(
                    "prepare", {"workspace": workspace, "title": title},
                    cwd=workspace, timeout=min(300.0, max(60.0, timeout)))
            except Exception as exc:
                task["status"] = STATUS_FAILED
                task["last_error"] = f"prepare failed: {type(exc).__name__}: {exc}"
                store.save(task)
                conversation.add("ERROR", task["last_error"], 0)
                events.append_record({
                    "ts": utc_now(), "source": "lifecycle", "lifecycle": "prepare_error",
                    "backend": backend, "workspace": workspace, "error": task["last_error"],
                })
                return summary(task, store, ok=False, command="prepare",
                               error=task["last_error"], extra={"backend": backend})
            events.append_record({
                "ts": utc_now(), "source": "lifecycle", "lifecycle": "prepare",
                "backend": backend, "workspace": workspace,
                "returncode": call.returncode, "events": call.events,
            })
            if not _helper_call_ok(call):
                task["status"] = STATUS_FAILED
                task["last_error"] = _helper_call_error(call)
                store.save(task)
                conversation.add("ERROR", task["last_error"], 0)
            else:
                value = call.result if isinstance(call.result, dict) else {}
                session_id = value.get("sessionId") or call.session_id
                workspace_id = value.get("workspaceId") or call.workspace_id
                if not session_id:
                    raise TaskError("the Desktop helper returned no session id")
                task["session_id"] = validate_session_id(str(session_id))
                task["workspace_id"] = str(workspace_id) if workspace_id else None
                task["status"] = STATUS_PREPARED
                task["last_error"] = None
                store.save(task)
                conversation.add(
                    "PREPARED",
                    "A Desktop session with no rounds was created for this task. No "
                    "model was called.\n"
                    f"workspace_id: {task.get('workspace_id')}\n"
                    f"session_id: {task.get('session_id')}\n"
                    "Pick the model/thinking level with `select-model` before the "
                    "first `send` if you need a specific one. A session that has "
                    "not run a turn does not appear in the Desktop sidebar; the "
                    "task id is the handle. Then run send with the first-round "
                    "brief.",
                    0,
                )
        finally:
            conversation.close()
            events.close()
        if call is not None:
            _require_helper_usage(call)

    if task.get("status") == STATUS_FAILED:
        return summary(task, store, ok=False, command="prepare",
                       error=task.get("last_error"),
                       extra={"backend": backend, "workspace_id": task.get("workspace_id")})
    return summary(
        task, store, ok=True, command="prepare", reply="",
        extra={
            "backend": backend,
            "session_id": task.get("session_id"),
            "workspace_id": task.get("workspace_id"),
            "model_selection": (
                "untouched; a session that has not run a turn cannot be given a "
                "model from inside Desktop, so pass --provider/--model to "
                "`select-model` before the first `send` if the user asked for a "
                "specific one (otherwise Desktop's default is used)"
            ),
            "next": "send --task <id> --workspace <ws> --message-file <first brief>",
        },
    )


def _helper_call_ok(call: DesktopHelperCall) -> bool:
    return (not call.timed_out and call.error is None and call.returncode == 0
            and call.result is not None)


def _require_helper_usage(call: DesktopHelperCall) -> None:
    """Surface the helper's own argument validation as a usage error.

    The helper validates a model/provider/reasoning effort against the live
    Desktop catalog and exits 2 for a bad choice; that is a caller mistake and
    must not be reported as an execution failure.
    """
    if call.returncode == EXIT_USAGE:
        raise UsageError(_helper_call_error(call))


def _helper_call_error(call: DesktopHelperCall) -> str:
    if call.error:
        return call.error
    if call.returncode not in (0, None):
        tail = call.stderr_tail.strip()[-300:]
        return (f"the Desktop helper exited with code {call.returncode}"
                + (f": {tail}" if tail else ""))
    return "the Desktop helper returned no result"


def _models(ctx: Context, args: argparse.Namespace) -> dict[str, Any]:
    """List the live Desktop model catalog.  No inference is performed."""
    backend = resolve_command_backend(ctx, args)
    if backend != BACKEND_DESKTOP:
        raise UsageError(
            "`models` reads the Desktop catalog; the headless CLI has no catalog "
            "of its own. Run it without --backend headless."
        )
    call = ctx.desktop_invoke("models", {}, timeout=120.0, cwd=os.getcwd())
    _require_helper_usage(call)
    if not _helper_call_ok(call):
        return {"ok": False, "command": "models", "backend": backend,
                "error": _helper_call_error(call)}
    catalog = call.result if isinstance(call.result, dict) else {}
    return {
        "ok": True,
        "command": "models",
        "backend": backend,
        "endpoint_file": str(ctx.desktop_endpoint) if ctx.desktop_endpoint else None,
        "default": catalog.get("default"),
        "providers": catalog.get("routableProviders"),
        "groups": catalog.get("groups"),
        "note": "read-only; select a model with `select-model`, or in the Desktop window",
    }


def _select_model(ctx: Context, args: argparse.Namespace) -> dict[str, Any]:
    """Request a model for one Desktop task's session.  Never called by `send`.

    Records only `selected_model`; the model Desktop really used is reported by
    each turn's header event and stays in `actual_model`.
    """
    store = ctx.store
    store.ensure()
    task_id = validate_task_id(args.task)
    backend = resolve_command_backend(ctx, args)
    if backend != BACKEND_DESKTOP:
        raise UsageError("select-model is a Desktop-only command")
    provider = str(args.provider)
    model = str(args.model)
    effort = getattr(args, "reasoning_effort", None)

    with store.lock(task_id):
        task = store.load(task_id)
        if args.workspace:
            ensure_workspace_match(task, require_workspace(args.workspace))
        task_backend(task)
        if backend != task_backend(task):
            raise UsageError(
                f"task {task_id} is bound to the {task_backend(task)!r} backend"
            )
        session_id = task.get("session_id")
        if not session_id:
            raise UsageError(
                f"task {task_id} has no Desktop session yet; run `prepare` or `start` first"
            )
        workspace = str(task.get("workspace") or os.getcwd())
        payload: dict[str, Any] = {"sessionId": session_id, "provider": provider,
                                   "model": model}
        if effort is not None:
            payload["reasoningEffort"] = effort
        call = ctx.desktop_invoke("select-model", payload, cwd=workspace, timeout=120.0)
        conversation = ConversationLog(Path(store.logs(task_id)["conversation_md"]))
        events = LogWriter(Path(store.logs(task_id)["events_jsonl"]))
        try:
            events.append_record({
                "ts": utc_now(), "source": "lifecycle", "lifecycle": "select_model",
                "requested": payload, "returncode": call.returncode,
                "selected_model": ((call.result or {}).get("selected")
                                   if isinstance(call.result, dict) else None),
                "ok": _helper_call_ok(call), "events": call.events,
            })
            if not _helper_call_ok(call):
                error = _helper_call_error(call)
                conversation.add("MODEL SELECTION FAILED", error,
                                 int(task.get("rounds") or 0))
                _require_helper_usage(call)
                return summary(task, store, ok=False, command="select-model",
                               error=error,
                               extra={"requested_model": payload})
            selected = None
            if isinstance(call.result, dict):
                selected = call.result.get("selected")
            # Only the *requested* model is recorded here.  `actual_model` is
            # filled in exclusively by a turn's protocol header event, so a
            # later selection can never erase what the previous round really
            # ran with.
            task["selected_model"] = selected or {
                "provider": provider, "model": model,
                **({} if effort is None else {"reasoningEffort": effort})}
            store.save(task)
            conversation.add(
                "MODEL SELECTED",
                json.dumps(task["selected_model"], ensure_ascii=False)
                + " (requested for this Desktop session; applies to later turns "
                  "and never rewrites the last actual model)",
                int(task.get("rounds") or 0),
            )
        finally:
            conversation.close()
            events.close()

    return summary(
        task, store, ok=True, command="select-model", reply="",
        extra={"selected_model": task.get("selected_model")},
    )


def _turn_summary(task: dict[str, Any], store: TaskStore, reply: str,
                  command: str) -> dict[str, Any]:
    return summary(
        task, store, reply=reply, ok=task.get("status") in TURN_SUCCESS_STATUSES,
        error=task.get("last_error"), command=command,
        extra={
            "rounds": task.get("rounds"),
            "max_rounds": task.get("max_rounds"),
            "classification": task.get("classification"),
        },
    )


def _check_can_run(task: dict[str, Any], recover: bool) -> None:
    """Gate a `send` before anything is launched.

    Recovery is explicit: a stale `running` state or a previously failed run may
    already have produced side effects, so both require `--recover`.  The round
    limit applies to every status, including recovery.
    """
    status = task.get("status")
    task_id = task.get("id")
    if status == STATUS_APPROVED:
        raise UsageError(
            f"task {task_id} is approved; send is refused. Start a new task."
        )

    if status == STATUS_RUNNING or status in NEEDS_RECOVER:
        if not recover:
            raise UsageError(
                f"task {task_id} is in state {status!r}; a previous run may have "
                "already produced side effects. Re-run with --recover to proceed."
            )
        if not task.get("session_id"):
            raise UsageError(
                f"task {task_id} has no established DSH session to recover; a new "
                "session cannot be attached to this task. Start a new task and "
                "include a summary of what the failed run may already have done."
            )

    rounds = int(task.get("rounds") or 0)
    max_rounds = int(task.get("max_rounds") or DEFAULT_MAX_ROUNDS)
    if rounds >= max_rounds:
        raise UsageError(
            f"task {task_id} reached its round limit ({rounds}/{max_rounds}); "
            "review the existing work or start a new task."
        )


def _send(ctx: Context, args: argparse.Namespace) -> dict[str, Any]:
    timeout = float(args.timeout)
    if timeout <= 0 or math.isinf(timeout) or math.isnan(timeout):
        raise UsageError(f"--timeout must be a positive finite number: {args.timeout!r}")
    store = ctx.store
    store.ensure()
    task_id = validate_task_id(args.task)
    workspace = require_workspace(args.workspace)
    message = read_message_file(args.message_file)

    with store.lock(task_id):
        task = store.load(task_id)
        ensure_workspace_match(task, workspace)
        # Refuses a backend switch; the recorded backend wins for compatibility.
        resolve_command_backend(ctx, args, task=task)
        _check_can_run(task, bool(args.recover))
        if args.recover:
            events = LogWriter(Path(store.logs(task_id)["events_jsonl"]))
            events.append_record({
                "ts": utc_now(), "source": "lifecycle",
                "lifecycle": "recover", "previous_status": task.get("status"),
                "previous_error": task.get("last_error"),
                "round": int(task.get("rounds") or 0),
            })
            events.close()
            task["last_error"] = None
            if task.get("status") in NEEDS_RECOVER | {STATUS_RUNNING}:
                task["status"] = STATUS_NEW
            store.save(task)
        try:
            task, reply = run_turn(ctx, task, message, timeout=timeout,
                                   first=_is_first_turn(task))
        except BaseException as exc:
            return summary(task, store, ok=False, command="send",
                           error=f"runner crashed: {type(exc).__name__}: {exc}")

    return _turn_summary(task, store, reply, "send")


def evidence_module():
    """Load the adjacent stdlib-only reader, including when imported by tests."""
    spec = importlib.util.spec_from_file_location(
        "dsh_evidence", Path(__file__).with_name("dsh_evidence.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _observe(ctx: Context, args: argparse.Namespace) -> dict[str, Any]:
    reader = evidence_module()
    try:
        return reader.observe(ctx.store, validate_task_id(args.task),
                              args.after, args.wait)
    except reader.EvidenceError as exc:
        raise UsageError(str(exc)) from exc


def _review(ctx: Context, args: argparse.Namespace) -> dict[str, Any]:
    """Record GPT's evidence/verdict.  Never calls DSH."""
    store = ctx.store
    store.ensure()
    task_id = validate_task_id(args.task)
    workspace = require_workspace(args.workspace)
    message = read_message_file(args.message_file)

    with store.lock(task_id):
        task = store.load(task_id)
        ensure_workspace_match(task, workspace)
        if task.get("status") == STATUS_APPROVED:
            raise UsageError(f"task {task_id} is already approved")
        proof = None
        if args.approve:
            reader = evidence_module()
            try:
                proof = reader.approval_evidence(
                    task, task_id, Path(store.logs(task_id)["events_jsonl"]))
            except reader.EvidenceError as exc:
                raise UsageError(f"approval refused: {exc}") from exc
        conversation = ConversationLog(Path(store.logs(task_id)["conversation_md"]))
        events = LogWriter(Path(store.logs(task_id)["events_jsonl"]))
        try:
            conversation.add("REVIEWER EVIDENCE", message,
                             int(task.get("rounds") or 0))
            verdict = "APPROVED" if args.approve else "NOT_APPROVED"
            if args.approve:
                conversation.add(
                    "REVIEWER VERDICT",
                    "APPROVED by reviewer. DSH completion alone is not approval; "
                    "this verdict was issued explicitly with --approve.",
                    int(task.get("rounds") or 0),
                )
                task["status"] = STATUS_APPROVED
                task["last_error"] = None
            else:
                conversation.add(
                    "REVIEWER VERDICT",
                    "NOT APPROVED (evidence recorded; task remains open for more "
                    "DSH work).",
                    int(task.get("rounds") or 0),
                )
            events.append_record({
                "ts": utc_now(), "source": "reviewer", "lifecycle": "review",
                "round": int(task.get("rounds") or 0),
                "verdict": verdict, "approved": bool(args.approve),
                "dsh_invoked": False,
                "evidence": proof,
            })
            store.save(task)
        finally:
            conversation.close()
            events.close()

    return summary(task, store, reply="", ok=True, command="review",
                   extra={"verdict": "APPROVED" if args.approve else "NOT_APPROVED",
                          "dsh_invoked": False,
                          "rounds": task.get("rounds"),
                          "max_rounds": task.get("max_rounds")})


def _show(ctx: Context, args: argparse.Namespace) -> dict[str, Any]:
    task_id = validate_task_id(args.task)
    task = ctx.store.load(task_id)
    payload = summary(task, ctx.store, ok=True, command="show")
    payload["task"] = task
    return payload


def _list(ctx: Context, args: argparse.Namespace) -> dict[str, Any]:
    tasks = ctx.store.all_tasks()
    if args.workspace:
        workspace = require_workspace(args.workspace)
        tasks = [t for t in tasks if t.get("workspace") == workspace]
    tasks.sort(key=lambda t: str(t.get("updated_at") or ""), reverse=True)
    return {
        "ok": True,
        "command": "list",
        "count": len(tasks),
        "tasks": [
            {
                "task_id": t.get("id"),
                "title": t.get("title"),
                "backend": task_backend(t),
                "status": t.get("status"),
                "workspace": t.get("workspace"),
                "workspace_id": t.get("workspace_id"),
                "session_id": t.get("session_id"),
                "selected_model": t.get("selected_model"),
                "actual_model": t.get("actual_model"),
                "rounds": t.get("rounds"),
                "updated_at": t.get("updated_at"),
                "logs": ctx.store.logs(str(t.get("id"))),
            }
            for t in tasks
        ],
        "state_root": str(ctx.store.root),
    }


